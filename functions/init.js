// ======================= 数据初始化 =======================
export async function onRequest(context) {
  const { env } = context;

  try {
    // 1. 建表
    await env.DB.exec(`
      CREATE TABLE IF NOT EXISTS content_library (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        series_id TEXT NOT NULL,
        title TEXT NOT NULL,
        description TEXT,
        mood_tag TEXT,
        cost_time TEXT,
        pushed INTEGER DEFAULT 0,
        push_date TEXT,
        created_at DATETIME DEFAULT CURRENT_TIMESTAMP
      )
    `);

    // 2. 检查是否已有数据
    const count = await env.DB.prepare('SELECT COUNT(*) as total FROM content_library').first();
    if (count && count.total > 0) {
      return new Response(JSON.stringify({
        message: `✅ 数据已存在，共 ${count.total} 条，无需重复初始化`,
        count: count.total
      }), {
        status: 200,
        headers: { 'Content-Type': 'application/json' }
      });
    }

    // 3. 把书籍数据转换为与 SEED_DATA 相同的格式
    //    归入系列 E（必读书目），description 拼接作者/评分/出版年份
    const BOOKS_FORMATTED = BOOKS_RAW.map(b => ({
      series_id: 'E',
      title: b.t,
      desc: `${b.a} · ${b.p} · ⭐${b.r}｜${b.s}`,
      mood: b.g,
      cost: '📖 阅读'
    }));

    // 4. 过滤掉系列 E 中与原有数据重复的书籍
    const originalE_Titles = new Set(
      SEED_DATA.filter(d => d.series_id === 'E').map(d => d.title)
    );
    const NEW_BOOKS = BOOKS_FORMATTED.filter(b => !originalE_Titles.has(b.title));

    // 5. 合并所有数据
    const ALL_DATA = [...SEED_DATA, ...NEW_BOOKS];

    // 6. 批量插入
    const stmt = env.DB.prepare(
      'INSERT INTO content_library (series_id, title, description, mood_tag, cost_time) VALUES (?, ?, ?, ?, ?)'
    );
    const batch = ALL_DATA.map(item =>
      stmt.bind(item.series_id, item.title, item.desc, item.mood, item.cost)
    );
    await env.DB.batch(batch);

    return new Response(JSON.stringify({
      message: `✅ 数据初始化成功！原有 ${SEED_DATA.length} 条 + 新增书籍 ${NEW_BOOKS.length} 本，共 ${ALL_DATA.length} 条`,
      originalCount: SEED_DATA.length,
      newBooksCount: NEW_BOOKS.length,
      totalCount: ALL_DATA.length
    }), {
      status: 200,
      headers: { 'Content-Type': 'application/json' }
    });

  } catch (error) {
    return new Response(JSON.stringify({
      error: `❌ 初始化失败: ${error.message}`
    }), {
      status: 500,
      headers: { 'Content-Type': 'application/json' }
    });
  }
}
